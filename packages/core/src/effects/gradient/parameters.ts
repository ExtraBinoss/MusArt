import type { EffectParameter, NumberEffectParameter } from "../definition";
import { GRADIENT_STYLES, GRADIENT_TREATMENTS, type GradientSettingKey } from "./model";
import { GRADIENT_PRESETS } from "./presets";

function number(
  key: GradientSettingKey,
  value: number,
  min: number,
  max: number,
  step = 0.01,
  unit = "",
  treatments?: readonly string[],
): NumberEffectParameter {
  return {
    kind: "number",
    scope: "settings",
    key,
    default: value,
    labelKey: `gradientFx:parameter.${key}`,
    min,
    max,
    step,
    displayScale: 1,
    unit,
    ...(treatments ? { visibleWhen: { key: "treatment", values: treatments } } : {}),
  };
}
const treatment = (
  key: GradientSettingKey,
  value: number,
  min: number,
  max: number,
  choices: readonly string[],
  step = 0.01,
) => number(key, value, min, max, step, "", choices);
